const panel = (inner) => gen(16, 16, (x, y) => {
  if (x === 0 || y === 0 || x === 15 || y === 15) return '1';
  if (x === 1 || y === 1) return '3';
  const r = inner && inner[y - 2];
  if (r && x >= 2 && x < 14 && r[x - 2] !== '.') return r[x - 2];
  return '2';
});

